#!/usr/bin/env python3
"""Frozen LaTeX-escaping metadata generator (metadata.json -> metadata.tex).

Accepts ONLY four literal string fields: author, affiliation, ai_disclosure, repo_url.
Rejects any raw TeX command tokens (backslash, braces), any ASCII/Unicode control
characters (including form feed, tab, CR, LF, NUL, DEL), and strictly escapes
remaining LaTeX special characters before emitting paper/metadata.tex.
"""
from __future__ import annotations

import json
import sys
import unicodedata
from pathlib import Path

REQUIRED_KEYS = ("author", "affiliation", "ai_disclosure", "repo_url")
FORBIDDEN_CHARS = ("\\", "{", "}")
ESCAPE_MAP = {
    "&": r"\&",
    "%": r"\%",
    "$": r"\$",
    "#": r"\#",
    "_": r"\_",
    "~": r"\textasciitilde{}",
    "^": r"\textasciicircum{}",
}


def validate_and_escape(key: str, val: object) -> str:
    if not isinstance(val, str):
        raise SystemExit(f"REJECT: metadata field '{key}' must be a JSON string.")
    s = val.strip()
    if not s:
        raise SystemExit(f"REJECT: metadata field '{key}' must be non-empty.")
    if len(s) > 1500:
        raise SystemExit(f"REJECT: metadata field '{key}' exceeds 1500 chars.")
    for c in val:
        if ord(c) < 32 or ord(c) == 127 or unicodedata.category(c).startswith("C"):
            raise SystemExit(
                f"REJECT: metadata field '{key}' contains forbidden control character U+{ord(c):04X}."
            )
    for ch in FORBIDDEN_CHARS:
        if ch in s:
            raise SystemExit(
                f"REJECT: metadata field '{key}' contains forbidden TeX control character {ch!r}."
            )
    return "".join(ESCAPE_MAP.get(c, c) for c in s)


def render_metadata(paper_dir: Path) -> Path:
    meta_json = paper_dir / "metadata.json"
    if not meta_json.is_file():
        raise SystemExit(f"REJECT: missing {meta_json}")
    data = json.loads(meta_json.read_text(encoding="utf-8"))
    if not isinstance(data, dict):
        raise SystemExit("REJECT: metadata.json root must be a JSON object.")
    extra = set(data.keys()) - set(REQUIRED_KEYS)
    missing = set(REQUIRED_KEYS) - set(data.keys())
    if extra or missing:
        raise SystemExit(f"REJECT: metadata.json keys mismatch (missing={sorted(missing)}, extra={sorted(extra)}).")

    escaped = {k: validate_and_escape(k, data[k]) for k in REQUIRED_KEYS}
    lines = [
        "% AUTO-GENERATED by frozen scripts/render_metadata.py from paper/metadata.json.",
        "% Do not hand-edit; edit paper/metadata.json and run scripts/render_metadata.py.",
        f"\\newcommand{{\\PaperAuthor}}{{{escaped['author']}}}",
        f"\\newcommand{{\\PaperAffiliation}}{{{escaped['affiliation']}}}",
        f"\\newcommand{{\\PaperAIDisclosure}}{{{escaped['ai_disclosure']}}}",
        f"\\newcommand{{\\PaperRepoURL}}{{{escaped['repo_url']}}}",
        "",
    ]
    out_path = paper_dir / "metadata.tex"
    out_path.write_text("\n".join(lines), encoding="utf-8")
    return out_path


def main() -> None:
    repo_root = Path(__file__).resolve().parent.parent
    paper_dir = Path(sys.argv[1]).resolve() if len(sys.argv) > 1 else (repo_root / "paper")
    out_path = render_metadata(paper_dir)
    print(f"RENDERED {out_path}")


if __name__ == "__main__":
    main()
